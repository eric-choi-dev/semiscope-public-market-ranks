const ignored=new Set(('a an and the for of common shares share stock beneficial interest interests ord ordinary '+
  'inc incorporated co corporation corp company llc plc lp trust fund de md ltd').split(' '));
function issuerWords(value){
  return String(value??'').normalize('NFKD').replace(/[\u0300-\u036f]/g,'').toLowerCase()
    .replace(/\bmulti[\s-]+media\b/g,'multimedia')
    .replace(/\blimited\b/g,'ltd').replace(/\bopp\b/g,'opportunities').replace(/\bstrategic?s?\b/g,'strategic')
    .split(/[^a-z0-9]+/).filter(word=>word&&!ignored.has(word));
}
function canonicalSymbol(value){
  return String(value??'').trim().toUpperCase().replace(/\$([A-Z0-9]+)$/,'-P$1')
    .replace(/\.PR\.?([A-Z0-9]+)$/,'-P$1').replace(/[./]/g,'-');
}
function nameAgrees(label,reference){
  const a=issuerWords(label), b=issuerWords(reference);
  if(!a.length||!b.length||a[0]!==b[0])return false;
  if(b.length===1)return a.length===1;
  const words=new Set(a);
  const shared=new Set(b.filter(word=>words.has(word))).size;
  return shared>=2 && shared>=Math.ceil(.5*new Set(b).size);
}

export function isRegisteredClosedEndFund(symbol,issuerName){
  const cik=securities.get(canonicalSymbol(symbol));
  if(cik===undefined)return false;
  if(!String(issuerName??'').trim())return true;
  return issuers.get(cik).some(name=>nameAgrees(issuerName,name));
}

export function closedEndFundRegistration(symbol){
  const cik=securities.get(canonicalSymbol(symbol));
  if(cik===undefined)return null;
  return {cik,issuer:issuers.get(cik)[0],source:CEF_REGISTRY.supplements.some(s=>s.cik===cik)?'filing':'annual'};
}
